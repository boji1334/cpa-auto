function Write-ComposeFile {
    $compose = @'
services:
  cli-proxy-api:
    image: "${CPA_IMAGE:-eceasy/cli-proxy-api:latest}"
    container_name: cli-proxy-api
    pull_policy: always
    restart: unless-stopped
    environment:
      TZ: "${TZ:-Asia/Shanghai}"
      MANAGEMENT_PASSWORD: "${MANAGEMENT_PASSWORD:?MANAGEMENT_PASSWORD is required}"
      DEPLOY: "${DEPLOY:-}"
    ports:
      - "${BIND_HOST:-127.0.0.1}:${SERVER_PORT:-8317}:8317"
      - "${OAUTH_BIND_HOST:-127.0.0.1}:8085:8085"
      - "${OAUTH_BIND_HOST:-127.0.0.1}:1455:1455"
      - "${OAUTH_BIND_HOST:-127.0.0.1}:54545:54545"
      - "${OAUTH_BIND_HOST:-127.0.0.1}:51121:51121"
      - "${OAUTH_BIND_HOST:-127.0.0.1}:11451:11451"
    volumes:
      - ./config.yaml:/CLIProxyAPI/config.yaml
      - ./auths:/root/.cli-proxy-api
      - ./logs:/CLIProxyAPI/logs
    healthcheck:
      test: ["CMD-SHELL", "wget -q -T 5 -O - http://127.0.0.1:8317/healthz >/dev/null 2>&1 || exit 1"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 20s
'@
    Set-Content -Path "docker-compose.yml" -Value $compose -Encoding ascii
}

function Write-CaddyFiles {
    if (-not $script:UseCaddy) {
        return
    }

    $caddyCompose = @'
services:
  caddy:
    image: caddy:2-alpine
    container_name: cli-proxy-api-caddy
    restart: unless-stopped
    depends_on:
      - cli-proxy-api
    ports:
      - "${HTTP_PORT:-80}:80"
      - "${HTTPS_PORT:-443}:443"
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - ./caddy_data:/data
      - ./caddy_config:/config
    networks:
      - default
'@
    Set-Content -Path "docker-compose.caddy.yml" -Value $caddyCompose -Encoding ascii

    $caddyfile = @"
$Domain {
    encode gzip zstd
    reverse_proxy cli-proxy-api:8317
}
"@
    Set-Content -Path "Caddyfile" -Value $caddyfile -Encoding ascii
}

function Write-HelperScript {
    $helper = @'
param(
    [string]$Command = "help",
    [string]$Service = "cli-proxy-api"
)

$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

function Get-DotEnvValue([string]$Path, [string]$Key) {
    if (-not (Test-Path $Path)) {
        return ""
    }
    $escaped = [regex]::Escape($Key)
    foreach ($line in Get-Content -Path $Path) {
        if ($line -match "^$escaped=(.*)$") {
            return $Matches[1]
        }
    }
    return ""
}

$Domain = Get-DotEnvValue ".env" "DOMAIN"
$Mode = Get-DotEnvValue ".env" "MODE"
$Port = Get-DotEnvValue ".env" "SERVER_PORT"
$UseCaddy = -not [string]::IsNullOrWhiteSpace($Domain) -and (Test-Path "docker-compose.caddy.yml")

function Invoke-Compose([string[]]$ComposeArgs) {
    $args = @("compose", "-f", "docker-compose.yml")
    if ($script:UseCaddy) {
        $args += @("-f", "docker-compose.caddy.yml")
    }
    $args += $ComposeArgs
    & docker @args
    if ($LASTEXITCODE -ne 0) {
        throw "docker compose failed: $($ComposeArgs -join ' ')"
    }
}

function Show-Help {
    @"
Usage: .\cpactl.ps1 COMMAND

Commands:
  start       Start CPA
  stop        Stop CPA
  restart     Restart CPA
  status      Show container status
  logs        Follow CPA logs
  update      Pull latest image and restart
  health      Check /healthz
  url         Print access URL
  password    Print saved credentials
  backup      Create a zip backup in the current directory
  help        Show this help
"@
}

switch ($Command.ToLowerInvariant()) {
    "start" {
        Invoke-Compose @("up", "-d")
    }
    "stop" {
        Invoke-Compose @("down")
    }
    "restart" {
        Invoke-Compose @("restart")
    }
    "status" {
        Invoke-Compose @("ps")
    }
    "logs" {
        Invoke-Compose @("logs", "-f", $Service)
    }
    "update" {
        Invoke-Compose @("pull")
        Invoke-Compose @("up", "-d")
    }
    "health" {
        if ([string]::IsNullOrWhiteSpace($Port)) { $Port = "8317" }
        Invoke-RestMethod -Uri "http://127.0.0.1:$Port/healthz"
    }
    "url" {
        if (-not [string]::IsNullOrWhiteSpace($Domain)) {
            Write-Host "https://$Domain"
        }
        elseif ($Mode -eq "local") {
            Write-Host "http://localhost:$Port"
        }
        else {
            Write-Host "http://SERVER_IP:$Port"
        }
    }
    "password" {
        if (Test-Path ".credentials") {
            Get-Content ".credentials"
        }
        else {
            Write-Host "Open .env and check API_KEY / MANAGEMENT_PASSWORD."
        }
    }
    "backup" {
        $stamp = Get-Date -Format "yyyyMMdd-HHmmss"
        $backup = "cpa-backup-$stamp.zip"
        $paths = @(".env", ".credentials", "config.yaml", "docker-compose.yml", "docker-compose.caddy.yml", "Caddyfile", "auths", "logs", "caddy_data", "caddy_config") | Where-Object { Test-Path $_ }
        Compress-Archive -Path $paths -DestinationPath $backup -Force
        Write-Host "Backup created: $backup"
    }
    "help" {
        Show-Help
    }
    default {
        Write-Host "Unknown command: $Command"
        Show-Help
        exit 1
    }
}
'@
    Set-Content -Path "cpactl.ps1" -Value $helper -Encoding ascii
}

function Wait-ForHealth {
    if ($NoStart) {
        return
    }
    for ($i = 0; $i -lt 30; $i++) {
        try {
            Invoke-RestMethod -Uri "http://127.0.0.1:$Port/healthz" -TimeoutSec 3 | Out-Null
            return
        }
        catch {
            Start-Sleep -Seconds 2
        }
    }
    Write-Host "CPA did not answer http://127.0.0.1:$Port/healthz yet. Check .\cpactl.ps1 logs." -ForegroundColor Yellow
}

if (-not $NoStart) {
    Test-DockerReady
}

Write-Step "Preparing CPA Auto in $Dir"
New-Item -ItemType Directory -Force -Path $Dir | Out-Null
Set-Location $Dir
New-Item -ItemType Directory -Force -Path "auths", "logs" | Out-Null
if ($UseCaddy) {
    New-Item -ItemType Directory -Force -Path "caddy_data", "caddy_config" | Out-Null
}

if (Test-Path ".env") {
    $backup = ".env.backup.$(Get-Date -Format 'yyyyMMddHHmmss')"
    Copy-Item ".env" $backup
    Write-Step "Existing .env found, backup saved as $backup"
}
else {
    Set-Content -Path ".env" -Value @("# Generated by CPA Auto.", "# You can edit this file and rerun .\cpactl.ps1 restart.") -Encoding ascii
}

$ExistingApiKey = Get-DotEnvValue ".env" "API_KEY"
$ExistingManagementPassword = Get-DotEnvValue ".env" "MANAGEMENT_PASSWORD"

if ([string]::IsNullOrWhiteSpace($ApiKey)) { $ApiKey = $ExistingApiKey }
if ([string]::IsNullOrWhiteSpace($ApiKey)) { $ApiKey = "cpa-$(New-HexSecret 24)" }
if ([string]::IsNullOrWhiteSpace($ManagementPassword)) { $ManagementPassword = $ExistingManagementPassword }
if ([string]::IsNullOrWhiteSpace($ManagementPassword)) { $ManagementPassword = "cpa-mgmt-$(New-HexSecret 18)" }

Set-DotEnvValue ".env" "MODE" $Mode
Set-DotEnvValue ".env" "CPA_IMAGE" $Image
Set-DotEnvValue ".env" "BIND_HOST" $BindHost
Set-DotEnvValue ".env" "OAUTH_BIND_HOST" $OAuthBindHost
Set-DotEnvValue ".env" "SERVER_PORT" "$Port"
Set-DotEnvValue ".env" "DOMAIN" $Domain
Set-DotEnvValue ".env" "TZ" $Timezone
Set-DotEnvValue ".env" "API_KEY" $ApiKey
Set-DotEnvValue ".env" "MANAGEMENT_PASSWORD" $ManagementPassword
Set-DotEnvValue ".env" "HTTP_PORT" "80"
Set-DotEnvValue ".env" "HTTPS_PORT" "443"

Write-ConfigFile
Write-ComposeFile
Write-CaddyFiles
Write-HelperScript

if ($UseCaddy) {
    $AccessUrl = "https://$Domain"
}
elseif ($Mode -eq "local") {
    $AccessUrl = "http://localhost:$Port"
}
else {
    $AccessUrl = "http://SERVER_IP:$Port"
}

$credentials = @(
    "CPA_URL=$AccessUrl",
    "MANAGEMENT_URL=$AccessUrl/management.html",
    "API_KEY=$ApiKey",
    "MANAGEMENT_PASSWORD=$ManagementPassword",
    "INSTALL_DIR=$Dir"
)
Set-Content -Path ".credentials" -Value $credentials -Encoding ascii

if (-not $NoStart) {
    Write-Step "Pulling Docker images"
    Invoke-Compose @("pull")
    Write-Step "Starting CPA"
    Invoke-Compose @("up", "-d")
    Write-Step "Waiting for health check"
    Wait-ForHealth
    Write-Step "Container status"
    Invoke-Compose @("ps")
}
else {
    Write-Host "Files written, containers not started because -NoStart was used." -ForegroundColor Yellow
}

Write-Host ""
Write-Host "CPA is ready." -ForegroundColor Green
Write-Host ""
Write-Host "URL:                 $AccessUrl"
Write-Host "Management panel:    $AccessUrl/management.html"
Write-Host "Management password: $ManagementPassword"
Write-Host "API key:             $ApiKey"
Write-Host "Install dir:         $Dir"
Write-Host ""
Write-Host "Useful commands:"
Write-Host "  cd `"$Dir`""
Write-Host "  powershell -ExecutionPolicy Bypass -File .\cpactl.ps1 status"
Write-Host "  powershell -ExecutionPolicy Bypass -File .\cpactl.ps1 logs"
Write-Host "  powershell -ExecutionPolicy Bypass -File .\cpactl.ps1 update"
Write-Host "  powershell -ExecutionPolicy Bypass -File .\cpactl.ps1 password"
Write-Host ""
Write-Host "Credentials were saved to:"
Write-Host "  $Dir\.credentials"

if ($UseCaddy) {
    Write-Host ""
    Write-Host "Domain note: make sure $Domain points to this machine, and open TCP ports 80 and 443." -ForegroundColor Yellow
}

if (-not $OAuthPorts) {
    Write-Host ""
    Write-Host "OAuth note: helper callback ports are bound to 127.0.0.1 by default. Use -OAuthPorts if web-panel login needs direct callback access." -ForegroundColor Yellow
}
