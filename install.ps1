[CmdletBinding()]
param(
    [ValidateSet("local", "server")]
    [string]$Mode = "local",

    [string]$Dir = "",
    [int]$Port = 8317,
    [string]$Domain = "",
    [string]$ApiKey = "",
    [string]$ManagementPassword = "",
    [string]$Image = "eceasy/cli-proxy-api:latest",
    [string]$Timezone = "Asia/Shanghai",
    [switch]$OAuthPorts,
    [switch]$NoStart,
    [switch]$Help
)

$ErrorActionPreference = "Stop"

function Show-Help {
    @'
CPA Auto one-click installer for Windows PowerShell

Usage:
  powershell -ExecutionPolicy Bypass -File .\install.ps1
  powershell -ExecutionPolicy Bypass -File .\install.ps1 -Mode local -Port 8317
  powershell -ExecutionPolicy Bypass -File .\install.ps1 -Mode server -Domain cpa.example.com

Options:
  -Mode local|server       local binds to 127.0.0.1, server opens to the network.
  -Dir PATH                Install directory. Default: %USERPROFILE%\cpa-local.
  -Port PORT               Host port for CLIProxyAPI. Default: 8317.
  -Domain DOMAIN           Enable Caddy HTTPS reverse proxy for this domain.
  -ApiKey KEY              Client API key. Default: auto-generated.
  -ManagementPassword P    Management key for /management.html. Default: auto-generated.
  -Image IMAGE             Docker image. Default: eceasy/cli-proxy-api:latest.
  -Timezone TZ             Timezone. Default: Asia/Shanghai.
  -OAuthPorts              Expose OAuth helper callback ports on 0.0.0.0.
  -NoStart                 Write files but do not start containers.
  -Help                    Show this help.

Docker Desktop must be installed and running before using this script.
'@
}

if ($Help) {
    Show-Help
    exit 0
}

if (-not [string]::IsNullOrWhiteSpace($Domain)) {
    $Mode = "server"
}

if ([string]::IsNullOrWhiteSpace($Dir)) {
    if ($Mode -eq "server") {
        $Dir = Join-Path $env:USERPROFILE "cpa-server"
    }
    else {
        $Dir = Join-Path $env:USERPROFILE "cpa-local"
    }
}

$UseCaddy = -not [string]::IsNullOrWhiteSpace($Domain)
if ($Mode -eq "local" -or $UseCaddy) {
    $BindHost = "127.0.0.1"
}
else {
    $BindHost = "0.0.0.0"
}

if ($OAuthPorts) {
    $OAuthBindHost = "0.0.0.0"
}
else {
    $OAuthBindHost = "127.0.0.1"
}

function Write-Step([string]$Message) {
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function New-HexSecret([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $rng.GetBytes($buffer)
    }
    finally {
        $rng.Dispose()
    }
    return (($buffer | ForEach-Object { $_.ToString("x2") }) -join "")
}

function Get-DotEnvValue([string]$Path, [string]$Key) {
    if (-not (Test-Path $Path)) {
        return ""
    }
    $escaped = [regex]::Escape($Key)
    foreach ($line in Get-Content -Path $Path) {
        if ($line -match "^$escaped=(.*)$") {
            return $Matches[1]
        }
    }
    return ""
}

function Set-DotEnvValue([string]$Path, [string]$Key, [string]$Value) {
    $lines = @()
    if (Test-Path $Path) {
        $lines = @(Get-Content -Path $Path)
    }

    $escaped = [regex]::Escape($Key)
    $found = $false
    for ($i = 0; $i -lt $lines.Count; $i++) {
        if ($lines[$i] -match "^$escaped=") {
            $lines[$i] = "$Key=$Value"
            $found = $true
        }
    }

    if (-not $found) {
        $lines += "$Key=$Value"
    }

    Set-Content -Path $Path -Value $lines -Encoding ascii
}

function Test-DockerReady {
    if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
        throw "Docker was not found. On Windows/macOS, install and start Docker Desktop first: https://www.docker.com/products/docker-desktop/ . Then rerun this script."
    }

    & docker info *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker is installed but not running. Start Docker Desktop and wait until it says Docker is running, then rerun this script."
    }

    & docker compose version *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose v2 was not found. Update Docker Desktop, then rerun this script."
    }
}

function Invoke-Compose([string[]]$ComposeArgs) {
    $args = @("compose", "-f", "docker-compose.yml")
    if ($script:UseCaddy) {
        $args += @("-f", "docker-compose.caddy.yml")
    }
    $args += $ComposeArgs
    & docker @args
    if ($LASTEXITCODE -ne 0) {
        throw "docker compose failed: $($ComposeArgs -join ' ')"
    }
}

